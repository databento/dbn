    #[test]
    fn test_sentinels_are_null() {
        let mut record = decode::<MboMsg>("test_data.mbo.v3.dbn.zst").remove(0);
        record.price = UNDEF_PRICE;
        record.ts_recv = UNDEF_TIMESTAMP;
        for pretty_px in [false, true] {
            let batch = to_record_batch(std::slice::from_ref(&record), pretty_px).unwrap();
            assert!(batch.column_by_name("price").unwrap().is_null(0));
            assert!(batch.column_by_name("ts_recv").unwrap().is_null(0));
            assert!(!batch.column_by_name("ts_event").unwrap().is_null(0));
        }
    }

    #[test]
    fn test_px_field_metadata() {
        let schema = Mbp10Msg::arrow_schema(false);
        let field = schema.field_with_name("bid_px_09").unwrap();
        assert_eq!(*field.data_type(), DataType::Int64);
        assert!(field.is_nullable());
        assert_eq!(
            field.metadata()[FIXED_PRICE_SCALE_KEY],
            FIXED_PRICE_SCALE.to_string()
        );
        let schema = Mbp10Msg::arrow_schema(true);
        let field = schema.field_with_name("bid_px_09").unwrap();
        assert_eq!(*field.data_type(), DataType::Float64);
        assert!(field.metadata().is_empty());
    }
