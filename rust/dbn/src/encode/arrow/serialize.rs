//! Helpers for serializing DBN records into Arrow columnar arrays. This format
//! is also known as Arrow IPC or Feather v2 files.
//!
//! The [`ArrowSerialize`] trait can be derived with the `ArrowSerialize` macro in
//! `dbn-macros`.

