/// The field metadata key holding the scale of fixed-precision price columns.
pub const FIXED_PRICE_SCALE_KEY: &str = "databento:fixed_price_scale";

/// Trait for record types that can be serialized to the Arrow and Parquet columnar
/// formats. Columns are built one field at a time from a slice of rows.
///
/// Implementations are generated by the `ArrowSerialize` derive macro. Encoding
/// `WithTsOut<T>` produces a trailing `ts_out` column.
// `Sized` is required because `arrow_columns` reads `Self` out of each row.
pub trait ArrowSerialize: Sized {
    /// Pushes the Arrow [`Field`]s for this record type onto `out`. Price fields are
    /// `Float64` if `pretty_px` is `true` and `Int64` otherwise.
    fn arrow_fields(pretty_px: bool, out: &mut Vec<Field>);

    /// Builds one column per field from `rows`, reading this record out of each row
    /// with `get`, and pushes them onto `out` in the same order as
    /// [`arrow_fields()`](Self::arrow_fields).
    fn arrow_columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &Self + Copy,
        pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    );

    /// Returns the Arrow schema for this record type.
    fn arrow_schema(pretty_px: bool) -> SchemaRef {
        let mut fields = Vec::new();
        Self::arrow_fields(pretty_px, &mut fields);
        Arc::new(Schema::new(fields))
    }
}

/// Trait for struct field types that flatten into Arrow columns. Primitives are one
/// column, while nested structs and arrays of structs flatten into one column per
/// leaf field. The `ArrowSerialize` derive calls this trait for each field.
///
/// `V` is the Rust type of the field. It's `Self` except for the marker types
/// [`UnixNanos`], [`FixedPrice`], and [`CChar`], which give a `#[dbn(...)]`
/// serialization attribute precedence over the field's primitive type.
pub trait ArrowField<V: ?Sized = Self> {
    /// Pushes the Arrow [`Field`]s for a field named `name` of this type onto `out`.
    fn fields(name: &str, pretty_px: bool, out: &mut Vec<Field>);

    /// Builds the columns for this field from `rows`, reading the field out of each
    /// row with `get`, and pushes them onto `out`.
    fn columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &V + Copy,
        pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    );
}

/// A `#[dbn(unix_nanos)]` field: a nullable UTC nanosecond timestamp with
/// `UNDEF_TIMESTAMP` as null.
pub struct UnixNanos;

/// A `#[dbn(fixed_price)]` field: nullable `Int64` with [`FIXED_PRICE_SCALE_KEY`]
/// metadata, or `Float64` if `pretty_px`, with `UNDEF_PRICE` as null.
pub struct FixedPrice;

/// A `#[dbn(c_char)]` field: a string of the one ASCII character, or empty for NUL
/// and non-ASCII bytes.
pub struct CChar;

// `'static` because the closures over `rows` are higher-ranked over the row lifetime
impl<T: HasRType + ArrowSerialize + 'static> ArrowSerialize for WithTsOut<T> {
    fn arrow_fields(pretty_px: bool, out: &mut Vec<Field>) {
        T::arrow_fields(pretty_px, out);
        UnixNanos::fields("ts_out", pretty_px, out);
    }

    fn arrow_columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &Self + Copy,
        pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    ) {
        T::arrow_columns(rows, |r| &get(r).rec, pretty_px, out);
        UnixNanos::columns(rows, |r| &get(r).ts_out, pretty_px, out);
    }
}

impl<T: ArrowSerialize> ArrowField for T {
    fn fields(_name: &str, pretty_px: bool, out: &mut Vec<Field>) {
        T::arrow_fields(pretty_px, out);
    }

    fn columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &T + Copy,
        pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    ) {
        T::arrow_columns(rows, get, pretty_px, out);
    }
}

/// Arrays of nested structs, like the `levels` of `Mbp10Msg`, flatten into the
/// struct's columns suffixed with the zero-padded index, e.g. `bid_px_00`.
impl<T: ArrowSerialize + 'static, const N: usize> ArrowField for [T; N] {
    fn fields(_name: &str, pretty_px: bool, out: &mut Vec<Field>) {
        for i in 0..N {
            let start = out.len();
            T::arrow_fields(pretty_px, out);
            for field in &mut out[start..] {
                let name = format!("{}_{i:02}", field.name());
                field.set_name(name);
            }
        }
    }

    fn columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &[T; N] + Copy,
        pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    ) {
        for i in 0..N {
            T::arrow_columns(rows, |r| &get(r)[i], pretty_px, out);
        }
    }
}

macro_rules! impl_arrow_field_primitive {
    ($($ty:ty => $arrow_ty:ty),+ $(,)?) => {$(
        impl ArrowField for $ty {
            fn fields(name: &str, _pretty_px: bool, out: &mut Vec<Field>) {
                out.push(Field::new(name, <$arrow_ty>::DATA_TYPE, false));
            }

            fn columns<R>(
                rows: &[R],
                get: impl Fn(&R) -> &$ty + Copy,
                _pretty_px: bool,
                out: &mut Vec<ArrayRef>,
            ) {
                let values = rows.iter().map(|r| *get(r));
                out.push(Arc::new(PrimitiveArray::<$arrow_ty>::from_iter_values(values)));
            }
        }
    )+};
}

impl_arrow_field_primitive! {
    u8 => UInt8Type,
    u16 => UInt16Type,
    u32 => UInt32Type,
    u64 => UInt64Type,
    i8 => Int8Type,
    i16 => Int16Type,
    i32 => Int32Type,
    i64 => Int64Type,
}

impl ArrowField for FlagSet {
    fn fields(name: &str, pretty_px: bool, out: &mut Vec<Field>) {
        u8::fields(name, pretty_px, out);
    }

    fn columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &FlagSet + Copy,
        _pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    ) {
        let values = rows.iter().map(|r| get(r).raw());
        out.push(Arc::new(UInt8Array::from_iter_values(values)));
    }
}

macro_rules! impl_arrow_field_char_enum {
    ($($ty:ty),+ $(,)?) => {$(
        impl ArrowField for $ty {
            fn fields(name: &str, pretty_px: bool, out: &mut Vec<Field>) {
                CChar::fields(name, pretty_px, out);
            }

            fn columns<R>(
                rows: &[R],
                get: impl Fn(&R) -> &$ty + Copy,
                _pretty_px: bool,
                out: &mut Vec<ArrayRef>,
            ) {
                out.push(c_char_column(rows, |r| *get(r) as u8));
            }
        }
    )+};
}

impl_arrow_field_char_enum!(SecurityUpdateAction, UserDefinedInstrument);

impl<const N: usize> ArrowField for [c_char; N] {
    fn fields(name: &str, _pretty_px: bool, out: &mut Vec<Field>) {
        out.push(Field::new(name, DataType::Utf8, true));
    }

    fn columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &[c_char; N] + Copy,
        _pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    ) {
        let values = rows.iter().map(|r| match c_chars_to_str(get(r)) {
            Ok("") | Err(_) => None,
            Ok(s) => Some(s),
        });
        out.push(Arc::new(StringArray::from_iter(values)));
    }
}

impl ArrowField<u64> for UnixNanos {
    fn fields(name: &str, _pretty_px: bool, out: &mut Vec<Field>) {
        out.push(Field::new(
            name,
            DataType::Timestamp(TimeUnit::Nanosecond, Some("UTC".into())),
            true,
        ));
    }

    fn columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &u64 + Copy,
        _pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    ) {
        let values = rows.iter().map(|r| {
            let ts = *get(r);
            (ts != UNDEF_TIMESTAMP).then_some(ts as i64)
        });
        let array = TimestampNanosecondArray::from_iter(values).with_timezone("UTC");
        out.push(Arc::new(array));
    }
}

impl ArrowField<i64> for FixedPrice {
    fn fields(name: &str, pretty_px: bool, out: &mut Vec<Field>) {
        let field = if pretty_px {
            Field::new(name, DataType::Float64, true)
        } else {
            Field::new(name, DataType::Int64, true).with_metadata(HashMap::from([(
                FIXED_PRICE_SCALE_KEY.to_owned(),
                FIXED_PRICE_SCALE.to_string(),
            )]))
        };
        out.push(field);
    }

    fn columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &i64 + Copy,
        pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    ) {
        let prices = rows
            .iter()
            .map(|r| *get(r))
            .map(|px| (px != UNDEF_PRICE).then_some(px));
        if pretty_px {
            out.push(Arc::new(Float64Array::from_iter(
                prices.map(|px| px.map(px_to_f64)),
            )));
        } else {
            out.push(Arc::new(Int64Array::from_iter(prices)));
        }
    }
}

impl ArrowField<c_char> for CChar {
    fn fields(name: &str, _pretty_px: bool, out: &mut Vec<Field>) {
        out.push(Field::new(name, DataType::Utf8, false));
    }

    fn columns<R>(
        rows: &[R],
        get: impl Fn(&R) -> &c_char + Copy,
        _pretty_px: bool,
        out: &mut Vec<ArrayRef>,
    ) {
        out.push(c_char_column(rows, |r| *get(r) as u8));
    }
}

fn c_char_column<R>(rows: &[R], get: impl Fn(&R) -> u8) -> ArrayRef {
    let mut builder = StringBuilder::with_capacity(rows.len(), rows.len());
    for row in rows {
        let byte = [get(row)];
        if byte[0] == 0 || !byte[0].is_ascii() {
            builder.append_value("");
        } else {
            builder.append_value(std::str::from_utf8(&byte).unwrap_or(""));
        }
    }
    Arc::new(builder.finish())
}

